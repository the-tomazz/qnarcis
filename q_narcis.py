    def saveCredentialsIfValidAsync(self, uname, pwd, cfg):
        """
        If credentials came from the dialog (cfg is None), validate them in a background task
        using QGIS networking. On success, persist them via addConfig(uname, pwd). Silent on failure.
        """
        if cfg is not None:
            return

        login_service = self.profile.service('login')
        if not login_service.enabled:
            return
        login_url = login_service.url()
        header_user = login_service.field('user').encode("utf-8")
        header_password = login_service.field('password').encode("utf-8")
        resp_key = login_service.field('gsrv_key')

        def _check(un, pw):
            try:
                url = login_url
                req = QNetworkRequest(QUrl(url))
                req.setRawHeader(header_user, un.encode("utf-8"))
                req.setRawHeader(header_password, pw.encode("utf-8"))

                br = QgsBlockingNetworkRequest()
                status = br.get(req)
                if status == _QGS_NETWORK_NO_ERROR:
                    reply = br.reply()
                    data = reply.content().data()
                    try:
                        resp = json.loads(data.decode("utf-8", errors="ignore"))
                    except Exception:
                        resp = {}
                    return resp_key in resp
            except Exception:
                return False
            return False

        def _on_finished(task):
            try:
                ok = getattr(task, "taskFunResult", False)
                if ok:
                    try:
                        self.addConfig(uname, pwd)
                    except Exception:
                        QgsMessageLog.logMessage(
                            "Validated QNarcIS credentials could not be stored.",
                            "QNarcIS",
                            _QGIS_WARNING,
                        )
            finally:
                try:
                    if getattr(self, "_cred_save_task", None) is task:
                        self._cred_save_task = None
                except Exception:
                    self._cred_save_task = None

        cred_task = QNarcisTask(self.tr("Preverjanje prijave"), _check, [uname, pwd], _on_finished)
        self._cred_save_task = cred_task
        QgsApplication.taskManager().addTask(cred_task)

    def getCredentials(self):
        am  = QgsApplication.authManager()
        uname = None
