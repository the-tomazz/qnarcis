        layer = self.iface.activeLayer()

        # 1) Preverjanje sloja in tipa
        if layer is None:
            self.iface.messageBar().pushMessage("Napaka", "Noben sloj ni aktiven.", level=_QGIS_WARNING)
            return
        if layer.type() != _QGIS_VECTOR_LAYER:
            self.iface.messageBar().pushMessage("Napaka", "Izbrati je treba VEKTORSKI (poligonski) sloj.", level=_QGIS_WARNING)
            return

        wkb = QgsWkbTypes.flatType(layer.wkbType())
        allowed = (
            _QGIS_WKB_POINT, _QGIS_WKB_MULTIPOINT,
            _QGIS_WKB_LINESTRING, _QGIS_WKB_MULTILINESTRING,
            _QGIS_WKB_POLYGON, _QGIS_WKB_MULTIPOLYGON
        )
        if wkb not in allowed:
            self.iface.messageBar().pushMessage(
                "Napaka",
                "Izbrani sloj mora biti točkovni, linijski ali poligonski (vključno z Multi*).",
                level=_QGIS_WARNING
            )
            return

        # 1b) Opozorilo za CRS sloja (preveri CRS sloja, ne CRS projekta)
        send_layer_service = self.profile.service('send_layer')
        # Brez »accepted_crs« v profilu strežnik sprejme vse CRS (vgrajen profil: EPSG:3794).
        accepted_crs = [str(c).upper() for c in (send_layer_service.get('accepted_crs') or [])]
        accepted_srids = set()
        for crs_id in accepted_crs:
            if crs_id.startswith("EPSG:"):
                try:
                    accepted_srids.add(int(crs_id.split(":", 1)[1]))
                except ValueError:
                    pass
        layer_crs = layer.crs()
        is_accepted_crs = False
        if layer_crs is not None and layer_crs.isValid():
            authid = (layer_crs.authid() or "").upper()
            if authid in accepted_crs:
                is_accepted_crs = True
            else:
                try:
                    is_accepted_crs = int(layer_crs.postgisSrid()) in accepted_srids
                except Exception:
                    is_accepted_crs = False

        if accepted_crs and not is_accepted_crs:
            crs_label = "neznan CRS"
            if layer_crs is not None and layer_crs.isValid():
                crs_label = layer_crs.authid() or "neznan CRS"

            QMessageBox.warning(
                self.iface.mainWindow(),
                "QNarcIS",
                f"Napačen CRS sloja za pošiljanje ({crs_label}). Sistem sprejema le sloje v CRS {', '.join(accepted_crs)}.",
                _QMESSAGEBOX_OK
            )
            return

        # 2) Logika izbora + potrditve
        selected_only = True
        sel_count = len(layer.selectedFeatures())

        from .selection_confirm_dialog import SendSelectionDialog
        dlg = SendSelectionDialog(layer, sel_count, parent=self.iface.mainWindow())
        if _exec_dialog(dlg) != _QDIALOG_ACCEPTED:
            return

        selected_only = dlg.selected_only
        fid_field_name = dlg.fid_field_name  # None => uporabi feature.id()

        # 2b) Preverjanje imen atributov (server ne podpira nenavadnih imen)
        excluded_field_names = []
        field_names = [f.name() for f in layer.fields()]
        invalid_field_names = []
        for name in field_names:
            nm = str(name or "")
            if not nm or not re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', nm):
                invalid_field_names.append(nm)

        if invalid_field_names:
            bad_name = invalid_field_names[0] if invalid_field_names[0] else "<prazno>"
            reply = QMessageBox.warning(
                self.iface.mainWindow(),
                "QNarcIS",
                f"Sloj, ki ga pošiljate ima neveljavno ime atributa ({bad_name}). Ali želite poslati sloj brez tega atributa?",
                _QMESSAGEBOX_YES | _QMESSAGEBOX_NO,
                _QMESSAGEBOX_NO
            )
            if reply != _QMESSAGEBOX_YES:
                return
            excluded_field_names = invalid_field_names

        # 3) Poverilnice (obstoječi pristop)
        uname, pwd, cfg = self.getCredentials()
        if not uname or not pwd:
            return
        
        self.saveCredentialsIfValidAsync(uname, pwd, cfg)

        # 4) Zagon naloge (QgsTask) – z blokado ponovnega zagona
        try:
            upload_kwargs = dict(
                api_url=send_layer_service.url(),
                result_url=send_layer_service.get('result_url'),
                fields=send_layer_service.fields(),
            )
            t = LayerUploadTask(
                layer,
                username=uname,
                password=pwd,
                description="NARCIS: pošlji izbrane objekte" if selected_only else "NARCIS: pošlji celoten sloj",
                selected_only=selected_only,
                **upload_kwargs
            )

            setattr(t, "fid_field_name", fid_field_name)
            setattr(t, "excluded_field_names", excluded_field_names)

            self._upload_running = True

            # Robustno: počisti zaklep, ko status doseže "Complete" ali več (velja tudi za "Canceled"/"Terminated")
            def _maybe_clear(flag_status):
                try:
                    # flag_status je int (QgsTask.Status)
                    if int(flag_status) >= int(_QGSTASK_COMPLETE):
                        self._upload_running = False
                except Exception:
                    # če karkoli zataji, raje sprosti zaklep
                    self._upload_running = False

            try:
                t.statusChanged.connect(_maybe_clear)
                t.destroyed.connect(lambda *args, **kwargs: setattr(self, "_upload_running", False))
            except Exception as exc:
                QgsMessageLog.logMessage(
                    f"Could not connect upload task status handlers: {exc}",
                    "QNarcIS",
                    _QGIS_WARNING,
                )

            QgsApplication.taskManager().addTask(t)
            self._sending_task = t

        except Exception as e:
            self._upload_running = False
            QgsMessageLog.logMessage("Napaka pri zagonu naloge: {}".format(e), "QNarcIS", _QGIS_CRITICAL)
            self.iface.messageBar().pushMessage("QNarcIS", "Napaka pri zagonu naloge za pošiljanje sloja.", level=_QGIS_CRITICAL)

