    def add_cb_inside_url_values(self, source, key = "_cb", value = None):
        """
        Append/update ?_cb=... INSIDE every url='...'/url="..." occurrence
        in a QGIS WMS/WFS datasource string.
        """

        def _add_or_update_query_param(u, k, v):
            scheme, netloc, path, query, frag = urlsplit(u)
            q = dict(parse_qsl(query, keep_blank_values=True))
            q[k] = v
            return urlunsplit((scheme, netloc, path, urlencode(q, doseq=True), frag))
        
        if value is None:
            value = str(int(time.time()))

        def repl(m):
            quote = m.group(1)
            url   = m.group(2)
            new_u = _add_or_update_query_param(url, key, value)
            return f"url={quote}{new_u}{quote}"

        return _URL_RE.sub(repl, source)
    
    def handleTreeItemClick(self, layerName, qgzLayerId, modelIndex, model, callback=None, show_errors=True, mark_tree_status=True):
        if qgzLayerId and (layerName in self.layers or layerName in self.locked_layers):

            if not self.layersAreEnumerated:
                self.enumerateExistingLayers()

            layerData = self.layers.get(layerName)

            if qgzLayerId in self.locked_layers_by_id:
                layerData = self.locked_layers_by_id[qgzLayerId]

            if layerData is None:
                return False

            source = layerData['source']
            providerKey = layerData['providerKey']

            # ---- LOCKED LAYER LOGIC ----
            if layerData.get('locked'):
                # Try to find existing narcis_gsrv_* config
                auth_id = self.get_geoserver_credentials()
                if not auth_id:
                    if callback:
                        callback(None)
                    return False
                
                creds = self.geoserver_credentials
                
                diff = get_wms_layers_difference(source, providerKey, auth_id)

                def get_layer_data_from_root_type_name(locked_layers, diff, providerKey):

                    for ld in locked_layers:
                        type_name = ld.get('type_name') or extract_typename(ld.get('source'), providerKey)
                        ld['type_name'] = type_name
                        if type_name in diff:
                            return ld
                    
                    return None

                layerData = get_layer_data_from_root_type_name(self.locked_layers[layerName], diff, providerKey)
                
                if not layerData:
                    if show_errors:
                        self.iface.messageBar().pushMessage(
                            "QNarcIS",
                            self.tr("Napaka pri nalaganju zaščitenega sloja") + f": {layerName}. "
                            + self.tr("Za dostop do tega sloja nimate ustreznih pravic."),
                            level=_QGIS_CRITICAL
                        )
                    if callback:
                        callback(None)
                    return False
                
                source = layerData['source']
                
                source = self.update_layer_source_authcfg(source, auth_id)
                layerData['source'] = source
            # ---- END LOCKED LAYER LOGIC ----

            # ---- NEW: Clear stored invalid layers and reset color ----
            if 'layer' in layerData and layerData['layer'] is not None and not sip.isdeleted(layerData['layer']):
                layer = layerData['layer']
                if not layer.isValid():
                    layerData['layer'] = None
                    if mark_tree_status:
                        self.setTreeItemColorAndFont(None, model, modelIndex)
                    reload_required = True
                else:
                    self.iface.setActiveLayer(layer)
                    if callback:
                        callback(layer)
                    return True
            else:
                reload_required = True

            if reload_required:
                QgsMessageLog.logMessage('Loading ' + providerKey + ' layer: ' + layerName + ' ...\n' + 'Layer source: ' + layerData['source'], "QNarcIS", _QGIS_INFO)
                
                if layerData.get('locked'):
                    layerData['source'] = source = self.add_cb_inside_url_values(layerData['source'])

                if providerKey == 'WFS' or providerKey == 'arcgisfeatureserver':
                    layerData['layer'] = QgsVectorLayer(layerData['source'], layerName, providerKey)
                else:
                    layerData['layer'] = QgsRasterLayer(layerData['source'], layerName, providerKey)

            layer = layerData['layer']

            if layerData.get('locked'):
                layer.setName(layer.name() + " 🔒")

            treeItemColor = QColor(46,139,87)

            if layer.isValid():                
                root = group = QgsProject.instance().layerTreeRoot()
                for xmlItem in reversed(layerData['ancestors']):
                    groupName = xmlItem.get('name')
                    if xmlItem not in self._xml_group_by_element:
                        group = self._xml_group_by_element[xmlItem] = self.insertGroup(group, groupName, int(xmlItem.attrib['__ginx___']))
                    else:
                        if not sip.isdeleted(self._xml_group_by_element[xmlItem]):
                            group = self._xml_group_by_element[xmlItem]
                        else:
                            group = self._xml_group_by_element[xmlItem] = self.insertGroup(group, groupName, int(xmlItem.attrib['__ginx___']))

                if root.findLayer(layer.id()) is None:
                    mapLayer = QgsProject.instance().addMapLayer(layer, False)
                    if 'additionalData' in layerData:
                        additionalData = layerData['additionalData']
                        mapLayer.setMinimumScale(float(additionalData['minScale']))
                        mapLayer.setMaximumScale(float(additionalData['maxScale']))
                        mapLayer.setScaleBasedVisibility(True)

                    layerIndex = int(layerData['xmlitem'].attrib['__ginx___'])
                    pos = self.getLayerTreeItemPosition(group, layerIndex)
                    lid = layerData['xmlitem'].get('id')
                    qmlPath = os.path.join(self.plugin_dir,'qml',lid+'.qml')

                    group.insertLayer(pos, layer)
                    self.layerTreeIndexByTreeItemId[layer.id()] = layerIndex

                    root = QgsProject.instance().layerTreeRoot()
                    layerNode = root.findLayer(layer.id())
                    layerNode.setExpanded(False)

                    if os.path.exists(qmlPath):
                        layer.loadNamedStyle(qmlPath)
                
                self.iface.setActiveLayer(layer)
            else:
                if show_errors:
                    if layerData.get('locked'):
                        self.iface.messageBar().pushMessage(
                            "QNarcIS",
                            self.tr("Napaka pri nalaganju sloja") + f": {layerName}. "
                            + self.tr("Morda nimate dovolj pravic za dostop do tega sloja."),
                            level=_QGIS_CRITICAL
                        )
                    else:
                        self.iface.messageBar().pushMessage(
                            "Error",
                            self.tr("Napaka pri nalaganju sloja") + ": " + layerName,
                            level=_QGIS_CRITICAL
                        )
                
                treeItemColor = QColor(255,0,0)

            if mark_tree_status:
                self.setTreeItemColorAndFont(treeItemColor, model, modelIndex)

            if callback:
                callback(layer)

            return bool(layer and layer.isValid())

        return False

