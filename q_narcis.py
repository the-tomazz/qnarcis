    def addGeoserverConfig(self, user, key):
        am = QgsApplication.authManager()
        config_name = f'narcis_gsrv_{user}'
        cfg = QgsAuthMethodConfig()
        cfg.setName(config_name)
        cfg.setMethod('Basic')
        cMap = {'username': user, 'password': key, 'realm': ''}
        cfg.setConfigMap(cMap)
        result = am.storeAuthenticationConfig(cfg)
        # result is (success: bool, cfg: QgsAuthMethodConfig)
        if isinstance(result, tuple) and isinstance(result[1], QgsAuthMethodConfig):
            auth_id = result[1].id()
        else:
            self.iface.messageBar().pushMessage(
                "QNarcIS",
                self.tr("Napaka pri shranjevanju Geoserver avtentikacije – avtentikacijska konfiguracija ni bila ustvarjena."),
                level=_QGIS_CRITICAL
            )
            return None
        QgsApplication.authManager().clearCachedConfig(auth_id)
        QgsMessageLog.logMessage(f"Stored Geoserver config as {config_name} (id={auth_id})", "QNarcIS", _QGIS_INFO)
        return auth_id

    def update_layer_source_authcfg(self, source, new_authcfg_id):
        # Replace existing authcfg=... with new_authcfg_id, or add it if not present
        if "authcfg=" in source:
            new_source = re.sub(r"authcfg=([^\s'\"]+)", f"authcfg={new_authcfg_id}", source)
        else:
            # Add authcfg at the beginning (could be added elsewhere as needed)
            new_source = f"authcfg={new_authcfg_id} {source}"
        return new_source

    def deleteAllGeoserverConfigs(self):
        am = QgsApplication.authManager()
        configs = am.availableAuthMethodConfigs()
        for auth_id, config in configs.items():
            # config might be a string (name) or QgsAuthMethodConfig object
            if hasattr(config, 'name'):
                config_name = config.name()
            else:
                config_name = config
            if isinstance(config_name, str) and config_name.startswith('narcis_gsrv_'):
                am.removeAuthenticationConfig(auth_id)
                QgsApplication.authManager().clearCachedConfig(auth_id)

    def addTreeItems(self, parentTreeItem, xml, sub_folder=''):

        def getAncestors(item, layerItemData):
            # lxml exposes the parent chain natively via getparent(), so no
            # synthetic parent attribute is needed (lxml requires string values).
            node = item
            while node is not None:
                name = node.get('name')
                if name is not None:
                    layerItemData['ancestors'].append(node)
                node = node.getparent()
                

        for idx, child in enumerate(xml):
            if child.tag == 'layer-tree-group' or child.tag == 'layer-tree-layer':
                nodeName = child.get('name')
                providerKey = ''
                additionalData = {}
                scaleDependencyItemText = ''
                organizationItemText = ''
                ownerItemText = ''
                urlItemLink = ''
                urlItemDescription = ''
                stanjeItemText = ''
                # lxml attributes must be strings; the index is decoded with int().
                child.attrib['__ginx___'] = str(idx)
                nodeNameItem = QStandardItem(nodeName)

                append_row = True

                skip_layer = False

                if child.tag == 'layer-tree-layer':
                    
                    lid = child.get('id')

                    nodeNameItem.setData(lid, _QT_USER_ROLE +1)

                    providerKey = child.get('providerKey')
                    # skrito polje za iskanje »Vsa polja« (tehnično ime sloja)
                    try:
                        nodeNameItem.setData(extract_typename(child.get('source') or '', providerKey or '') or '', _QT_USER_ROLE + 2)
                    except Exception as exc:
                        QgsMessageLog.logMessage(f"Typename for search not available: {exc}", "QNarcIS", _QGIS_INFO)
                    layerItemData = {
                        'source': child.get('source'),
                        'providerKey': providerKey,
                        'xmlitem': child,
                        'ancestors':[]
                    }

                    additionalDataById = self.additionalDataById if not sub_folder else self.settingsAdditionalDataById

                    if lid in additionalDataById:
                        additionalData = additionalDataById[lid]
                        
                        locked = additionalData['locked'] if 'locked' in additionalData else False

                        if locked and 'authcfg' in layerItemData['source'] and not self.profile.enabled('login'):
                            # Profil nima prijave: zaščitenega sloja ni mogoče uporabiti,
                            # zato ga ne prikažemo in nikoli ne sprožimo prijave.
                            QgsMessageLog.logMessage(
                                f"Locked layer hidden (profile has no login service): {nodeName}",
                                "QNarcIS", _QGIS_INFO)
                            layerItemData['locked'] = True
                            skip_layer = True
                            append_row = False
                        elif locked and 'authcfg' in layerItemData['source']:
                            if not sub_folder:
                                self.locked_layers.setdefault(nodeName, [])
                                self.locked_layers_by_id[lid] = layerItemData
                                self.locked_layers[nodeName].append(layerItemData)
                            nodeNameItem.setIcon(self.lock_icon)
                            layerItemData['locked'] = True

                            if not sub_folder and nodeName in self.locked_layers and len(self.locked_layers[nodeName]) > 1:
                                append_row = False
                        else:
                            layerItemData['locked'] = False

                        layerItemData['additionalData'] = additionalData
                        scaleDependencyItemText = '(' + format_decimal(additionalData['minScale'])+', '+ format_decimal(additionalData['maxScale'])+']'
                        organizationItemText = additionalData['organization']
                        ownerItemText = additionalData['owner'] if 'owner' in additionalData else ''
                        urlItemLink = additionalData['url'] if 'url' in additionalData else ''
                        urlItemDescription = additionalData['description'] if 'description' in additionalData else ''
                        stanjeItemText = additionalData['stanje'] if 'stanje' in additionalData else ''

                    if not skip_layer:
                        getAncestors(xml, layerItemData)
